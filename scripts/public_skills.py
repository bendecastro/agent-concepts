#!/usr/bin/env python3
"""Generate and check the list of public skills and the skills each needs.

A public skill is a concept with `body/SKILL.md` whose CONCEPT.md frontmatter is
not `deployed: no` -- the same rule `deploy-local-skills.py` applies. Kernels
are injected rather than installed and have no SKILL.md, so they drop out.
A skill's needs are the targets of its `loads` edges in
concepts/relationships.json that are themselves public skills. Install methods
read the committed list; none keeps its own copy.
"""

from __future__ import annotations

import json
import re
from pathlib import Path


LIST_PATH = "concepts/public-skills.json"
GENERATED_NOTE = "GENERATED by `python3 scripts/lint.py --write-public-skills` -- do not edit by hand."

# An instruction to load another skill: "load `x`", "Load the `x` skill",
# "invoke `x`". Bare backticked names are excluded because bodies mention
# skills they hand off to or contrast with; negations ("do not load `x`") are
# excluded because they forbid the load.
_LOAD_REFERENCE = re.compile(r"(?<![\w-])(?:load|invoke)\s+(?:the\s+)?`/?([a-z0-9]+(?:-[a-z0-9]+)*)`", re.IGNORECASE)
_NEGATION = re.compile(r"\bnot\s+$", re.IGNORECASE)


def _marked_undeployed(concept: Path) -> bool:
    if not concept.is_file():
        return False
    lines = concept.read_text(encoding="utf-8").splitlines()
    if not lines or lines[0].strip() != "---":
        return False
    for line in lines[1:]:
        if line.strip() == "---":
            break
        key, _, value = line.partition(":")
        if key.strip() == "deployed":
            return value.strip() == "no"
    return False


def public_skills(root: Path) -> list[str]:
    return sorted(
        skill.parent.parent.name
        for skill in (root / "concepts").glob("*/body/SKILL.md")
        if not _marked_undeployed(skill.parent.parent / "CONCEPT.md")
    )


def _loads(root: Path) -> dict[str, set[str]]:
    graph = json.loads((root / "concepts" / "relationships.json").read_text(encoding="utf-8"))
    loads: dict[str, set[str]] = {}
    for edge in graph.get("edges", []):
        if edge.get("relation") == "loads":
            loads.setdefault(edge["from"], set()).add(edge["to"])
    return loads


def public_skill_list(root: Path) -> dict[str, list[str]]:
    names = public_skills(root)
    public = set(names)
    loads = _loads(root)
    return {name: sorted(loads.get(name, set()) & public) for name in names}


def render_list(root: Path) -> str:
    document = {"note": GENERATED_NOTE, "skills": public_skill_list(root)}
    return json.dumps(document, indent=2) + "\n"


def write_list(root: Path) -> Path:
    path = root / LIST_PATH
    path.write_text(render_list(root), encoding="utf-8")
    return path


def check_list(root: Path) -> list[str]:
    path = root / LIST_PATH
    if not path.is_file():
        return [f"missing {LIST_PATH}; run scripts/lint.py --write-public-skills"]
    if path.read_text(encoding="utf-8") != render_list(root):
        return [f"{LIST_PATH} is stale; run scripts/lint.py --write-public-skills"]
    return []


def unlisted_load_references(root: Path) -> list[str]:
    """Name each body that tells the agent to load a public skill it does not list as needed."""
    listing = public_skill_list(root)
    errors: list[str] = []
    for name, needs in listing.items():
        body = root / "concepts" / name / "body"
        for path in sorted(p for p in body.rglob("*.md") if p.is_file()):
            text = path.read_text(encoding="utf-8")
            for match in _LOAD_REFERENCE.finditer(text):
                target = match.group(1)
                if target == name or target not in listing or target in needs:
                    continue
                if _NEGATION.search(text[max(0, match.start() - 8):match.start()]):
                    continue
                line = text.count("\n", 0, match.start()) + 1
                errors.append(
                    f"{path.relative_to(root)}:{line}: {name} loads public skill `{target}` "
                    "without a `loads` edge in concepts/relationships.json"
                )
    return errors
